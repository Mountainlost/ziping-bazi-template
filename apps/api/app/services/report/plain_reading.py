def everyday_theme(label):
    return {'承载与压力需关注':'事情可能变多，先安排好时间和人手',
            '资源机会增加':'多留意新的合作和发展机会',
            '变化较明显':'工作或生活安排需要留出调整空间',
            '信息不足':'这段时间还缺少足够资料'}.get(label,label)


